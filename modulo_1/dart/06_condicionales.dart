void main() {
  int a = 2;
  if (a>2){
    print('a > 2 is true');
  }
  if (a<2){
    print('a < 2 is true');
  }
  if (a==2){
    print('a == 2 is true');
  }
  if (a<2){
    print('a > 2 is true');
  } else{
    print('a <= 2 is true');
  }
  if (a==2){
    print('a == 2 is true');
  }else {
    print('a != 2 is true');
  }
}
